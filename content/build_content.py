def validate(items, scenarios):
    ids = [i["id"] for i in items] + [s["id"] for s in scenarios]
    assert len(ids) == len(set(ids)), "duplicate ids"
    per_topic = {}
    for it in items:
        assert it["format"] in FORMATS, it["id"]
        assert it["key"] in it["options"], it["id"]
        wrong = set(it["options"]) - {it["key"]}
        assert wrong == set(it["misconceptions"]), f"{it['id']} misconceptions {wrong} vs {set(it['misconceptions'])}"
        assert it["topic"] in TOPICS, it["id"]
        per_topic[it["topic"]] = per_topic.get(it["topic"], 0) + 1
    assert all(v == 4 for v in per_topic.values()) and len(per_topic) == 10, per_topic
    for s in scenarios:
        for st in s["steps"]:
            if st["kind"] in ("interpret", "act"):
                assert st["key"] in st["options"], s["id"]
                wrong = set(st["options"]) - {st["key"]}
                assert wrong == set(st["misconceptions"]), s["id"]
            else:
                assert len(st["checkpoints"]) == 3, s["id"]
    return per_topic


